import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
const connection=JSON.parse(await readFile('.shopora-preview/connection.json','utf8'));
const {url,code}=connection;
assert.match(url,/^https:\/\/(?!api\.)[a-z0-9][a-z0-9-]+\.trycloudflare\.com$/,'Only the generated temporary HTTPS test site can be checked');
const request=(path,options={})=>fetch(url+path,{...options,signal:AbortSignal.timeout(15000)});
const post=(path,body,cookie='')=>request(path,{method:'POST',headers:{origin:url,'content-type':'application/json',cookie},body:JSON.stringify(body)});
const cookie=response=>response.headers.get('set-cookie')?.split(';')[0];
assert.equal((await request('/api/health')).status,200,'isolated database ready');
assert.equal((await request('/api/store/catalog')).status,401,'catalogue gated');
assert.equal((await request('/api/preview/inbox?email=check@example.test')).status,401,'simulated inbox gated');
const gate=await post('/api/preview/access',{code});assert.equal(gate.status,200);assert.match(gate.headers.get('set-cookie'),/; Secure/i);
const gateCookie=cookie(gate);assert.ok(gateCookie);
assert.equal((await request('/preview',{headers:{cookie:gateCookie}})).status,200);
assert.ok((await (await request('/api/store/catalog',{headers:{cookie:gateCookie}})).json()).products.length>0);
const email=`link-check-${randomUUID().slice(0,8)}@example.test`,password=`synthetic browser test ${randomUUID()}`;
assert.equal((await post('/api/owned-auth/register',{email},gateCookie)).status,200);
const mailbox=await (await request(`/api/preview/inbox?email=${encodeURIComponent(email)}`,{headers:{cookie:gateCookie}})).json();
assert.equal(mailbox.simulated,true);assert.ok(mailbox.data[0].subject.includes('SIMULATED EMAIL'));
const link=new URL(mailbox.data[0].body.match(/https?:\/\/[^\s]+/)[0]);assert.equal(link.origin,url);
const token=new URLSearchParams(link.hash.slice(1)).get('token');
assert.equal((await post('/api/owned-auth/verify',{token,password},gateCookie)).status,200);
const login=await post('/api/owned-auth/login',{email,password},gateCookie);assert.equal(login.status,200);assert.match(login.headers.get('set-cookie'),/^__Host-shopora_session=.*; Secure/i);
const authenticated=`${gateCookie}; ${cookie(login)}`;
assert.equal((await (await request('/api/owned-auth/session',{headers:{cookie:authenticated}})).json()).user.email,email);
assert.equal((await post('/api/owned-auth/logout',{},authenticated)).status,200);
assert.equal((await (await request('/api/owned-auth/session',{headers:{cookie:authenticated}})).json()).user,null);
console.log(JSON.stringify({url,passed:true,verified:['HTTPS health','preview access code and gated inbox','synthetic catalogue','captured verification email and correct HTTPS link','secure sign-in session','logout revocation']}));
